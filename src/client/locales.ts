/** A namespace-bound translator: key in, interpolated string out. */
export type Translate = (key: string, params?: Record<string, string | number>) => string

/**
 * Bind this plugin's translator.
 *
 * Returns a plain closure over the locale service. It deliberately does NOT
 * write the function onto `ctx`: a cordis context only exposes what it was
 * given with `provide`, and assigning an ad-hoc property to an activation's
 * context aborts the whole plugin boot.
 * @param locale - the client locale service.
 * @returns the namespace-bound translator.
 */
export function bindTranslator(locale: {
  bind(ns: string): (key: string, params?: Record<string, string | number>) => string
}): Translate {
  return locale.bind(LOCALE_NS)
}
