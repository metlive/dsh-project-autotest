/**
 * The conclusion report: `<workspace>/docs/autotest/report.md`.
 *
 * Where the seven-step flow asks "分析结果" and "跟踪 Bug", this file is the
 * artifact a reviewer reads: it answers, for one project, how far the pipeline
 * got, what the coverage commitment is, which cases are trustworthy, which
 * failed and why, and whether the defects are really closed.
 *
 * It is REGENERATED on every save from the same project document the page
 * edits, so the report can never describe a state the project is no longer in —
 * that is the whole reason it is rendered rather than typed by hand.
 *
 * @module dsh-project-autotest/report
 */
import {
  projectProgress,
  splitCases,
  STEP_IDS,
  type FailReason,
  type ProjectState,
  type StepId,
} from './wire.ts'

/** Stage titles per language, matching the workbench's stage rail. */
const STAGE: Record<'zh' | 'en', Record<StepId, string>> = {
  zh: {
    requirement: '产品文档 / 技术方案',
    cases: '设计测试用例',
    execution: '编写并执行测试脚本',
    bugs: '跟踪测试 Bug',
  },
  en: {
    requirement: 'Product docs / technical design',
    cases: 'Design test cases',
    execution: 'Write and run scripts (model)',
    bugs: 'Track test bugs',
  },
}

/**
 * Pick the report's language from a locale id.
 *
 * Prefixed because the Host build inlines every module into ONE scope, where
 * `export.ts` already owns a `language` helper.
 */
function reportLanguage(localeId: string): 'zh' | 'en' {
  return localeId.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/** A markdown table cell: escape pipes and collapse newlines. */
function cell(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim()
}

/** A status glyph a reviewer can scan. */
const GLYPH: Record<string, string> = { done: '✅', doing: '🟡', todo: '⬜', passed: '✅', failed: '❌', blocked: '⛔', untested: '⬜' }

/**
 * Render the report for one project.
 * @param project - the project document.
 * @param localeId - the locale id; anything not starting with `zh` renders English.
 * @returns the markdown body.
 */
export function renderReport(project: ProjectState, localeId: string, requirementDocs = 0): string {
  const lang = reportLanguage(localeId)
  const t = lang === 'zh'
  const stages = STAGE[lang]
  // The report shows DERIVED status, the same facts the page shows: a stored
  // status a person forgot to move would otherwise contradict the work.
  const statuses = deriveStageStatus(project, { documents: requirementDocs, hasNote: false })
  const withStatus: ProjectState = { ...project, steps: Object.fromEntries(STEP_IDS.map((id) => [id, { ...project.steps[id], status: statuses[id] }])) as ProjectState['steps'] }
  const progress = projectProgress(withStatus)
  const buckets = splitCases(project.cases)
  const casesById = new Map(project.cases.map((item) => [item.id, item]))
  const verified = project.cases.filter((item) => item.selfCheck.passOnGood && item.selfCheck.failOnBad).length
  const executed = project.cases.filter((item) => item.result !== 'untested').length
  const passed = project.cases.filter((item) => item.result === 'passed').length
  const failed = project.cases.filter((item) => item.result === 'failed').length
  const closed = project.defects.filter((item) => item.status === 'closed').length
  const regressed = project.defects.filter((item) => item.regression === 'passed').length

  /** The pass rate over executed cases, as a percentage string. */
  const passRate = executed === 0 ? '—' : `${Math.round((passed / executed) * 100)}%`

  /** `{ n/m }` the reviewer reads at a glance. */
  const ratio = (n: number, m: number): string => `${n}/${m}`

  const lines: string[] = []
  lines.push(t ? `# ${project.title} — 自动化测试结论报告` : `# ${project.title} — automation test report`)
  lines.push('')
  lines.push(t
    ? '> 本报告由「自动化测试」工作台在每次保存时自动生成，内容与 `project.json` 保持一致，请勿手工修改。'
    : '> Generated by the automation-test workbench on every save and kept in sync with `project.json`. Do not edit by hand.')
  lines.push('')
  lines.push(t ? `- 工作区：\`${project.path}\`` : `- Workspace: \`${project.path}\``)
  lines.push(t
    ? `- 生成时间：${new Date(project.updatedAt).toISOString()}`
    : `- Generated: ${new Date(project.updatedAt).toISOString()}`)
  lines.push(t
    ? `- 流程进度：${progress.done}/${progress.total}（${progress.percent}%）`
    : `- Pipeline: ${ratio(progress.done, progress.total)} (${progress.percent}%)`)
  lines.push('')

  // ---- the verdict, stated up front --------------------------------------
  lines.push(t ? '## 结论摘要' : '## Summary')
  lines.push('')
  lines.push(t ? '| 指标 | 数值 | 说明 |' : '| Metric | Value | Note |')
  lines.push('|---|---|---|')
  lines.push(t
    ? `| 覆盖率目标 | ${project.coverageTarget}% | 自动化粒度：${project.automationLevel === 'api' ? '接口级' : project.automationLevel === 'ui' ? 'UI 级' : '接口 + UI'} |`
    : `| Coverage target | ${project.coverageTarget}% | Level: ${project.automationLevel} |`)
  lines.push(t
    ? `| 用例总数 | ${project.cases.length} | 正向 ${buckets.positive.length} · 反向 ${buckets.negative.length} |`
    : `| Cases | ${project.cases.length} | positive ${buckets.positive.length} · negative ${buckets.negative.length} |`)
  lines.push(t
    ? `| 已执行 | ${ratio(executed, project.cases.length)} | 通过 ${passed} · 失败 ${failed} · 通过率 ${passRate} |`
    : `| Executed | ${ratio(executed, project.cases.length)} | passed ${passed} · failed ${failed} · pass rate ${passRate} |`)
  lines.push(t
    ? `| 脚本已自检 | ${ratio(verified, project.cases.length)} | 正确版本通过 且 缺陷版本失败 |`
    : `| Scripts self-checked | ${ratio(verified, project.cases.length)} | passes on good build AND fails on bad build |`)
  lines.push(t
    ? `| 缺陷闭环 | ${ratio(closed, project.defects.length)} | 回归通过 ${regressed} |`
    : `| Defects closed | ${ratio(closed, project.defects.length)} | regression passed ${regressed} |`)
  lines.push('')

  // ---- pipeline status ----------------------------------------------------
  lines.push(t ? '## 流程状态' : '## Pipeline status')
  lines.push('')
  lines.push(t ? '| # | 阶段 | 状态 | 备注 |' : '| # | Stage | Status | Note |')
  lines.push('|---|---|---|---|')
  STEP_IDS.forEach((id, index) => {
    const step = withStatus.steps[id]
    const label = t ? { todo: '未开始', doing: '进行中', done: '已完成' }[step.status] : { todo: 'to do', doing: 'in progress', done: 'done' }[step.status]
    lines.push(`| ${index + 1} | ${stages[id]} | ${GLYPH[step.status] ?? ''} ${label} | ${cell(step.note)} |`)
  })
  lines.push('')

  // ---- cases --------------------------------------------------------------
  const bucket = (kind: 'positive' | 'negative', items: typeof buckets.positive, title: string): void => {
    lines.push(`## ${title} (${items.length})`)
    lines.push('')
    if (items.length === 0) {
      lines.push(t ? '_暂无用例。_' : '_No cases yet._')
      lines.push('')
      return
    }
    lines.push(t
      ? '| 用例 | 方法 | 执行 | 自检 | 失败原因 | 预期结果 |'
      : '| Case | Technique | Result | Self-check | Cause | Expected |')
    lines.push('|---|---|---|---|---|---|')
    for (const item of items) {
      const selfCheck = item.selfCheck.passOnGood && item.selfCheck.failOnBad
        ? (t ? '已自检' : 'verified')
        : (t ? '未自检' : 'unverified')
      const cause = item.result === 'failed'
        ? (t ? { none: '未归因', product: '产品缺陷', script: '脚本问题', environment: '环境问题' }[item.failReason as FailReason] : item.failReason)
        : '—'
      lines.push(`| ${cell(item.title)} | ${item.technique} | ${GLYPH[item.result] ?? ''} ${item.result} | ${selfCheck} | ${cause} | ${cell(item.expected)} |`)
    }
    lines.push('')
    void kind
  }
  bucket('positive', buckets.positive, t ? '正向用例（优先实现）' : 'Positive cases')
  bucket('negative', buckets.negative, t ? '反向用例（分析筛选）' : 'Negative cases')

  // ---- defects ------------------------------------------------------------
  lines.push(t ? `## 缺陷跟踪 (${project.defects.length})` : `## Defects (${project.defects.length})`)
  lines.push('')
  if (project.defects.length === 0) {
    lines.push(t ? '_暂无缺陷。_' : '_No defects recorded._')
    lines.push('')
  } else {
    lines.push(t
      ? '| 缺陷 | 状态 | 关联用例 | 回归 | 需求偏离 |'
      : '| Defect | Status | Case | Regression | Requirement drift |')
    lines.push('|---|---|---|---|---|')
    for (const defect of project.defects) {
      const linked = casesById.get(defect.caseId)?.title ?? '—'
      const drift = defect.requirementChanged ? (t ? '⚠️ 是（脚本需同步）' : '⚠️ yes') : '—'
      lines.push(`| ${cell(defect.title)} | ${defect.status} | ${cell(linked)} | ${defect.regression} | ${drift} |`)
    }
    lines.push('')
  }

  // ---- the four reflow actions the flow depends on ------------------------
  const unverified = project.cases.filter((item) => !(item.selfCheck.passOnGood && item.selfCheck.failOnBad))
  const mistriaged = project.cases.filter((item) => item.result === 'failed' && (item.failReason === 'none' || item.failReason === 'script' || item.failReason === 'environment'))
  const blockedDefects = project.defects.filter((defect) => defect.requirementChanged && defect.regression === 'pending')
  lines.push(t ? '## 待办与风险' : '## Open items')
  lines.push('')
  // Stage progress is CONTEXT, not a finding: it is printed separately so the
  // ✅ verdict below speaks only about the test assets.
  const pendingStages = STEP_IDS.filter((id) => withStatus.steps[id].status !== 'done').map((id) => stages[id])
  const open: string[] = []
  if (unverified.length > 0) {
    open.push(t
      ? `${unverified.length} 条用例脚本未自检（正确版本通过 + 缺陷版本失败）：${unverified.map((item) => item.title).join('、')}`
      : `${unverified.length} unverified scripts: ${unverified.map((item) => item.title).join(', ')}`)
  }
  if (mistriaged.length > 0) {
    open.push(t
      ? `${mistriaged.length} 个失败未归因为产品缺陷，需回查脚本或环境：${mistriaged.map((item) => item.title).join('、')}`
      : `${mistriaged.length} failures not attributed to the product — check script or environment: ${mistriaged.map((item) => item.title).join(', ')}`)
  }
  if (blockedDefects.length > 0) {
    open.push(t
      ? `${blockedDefects.length} 个缺陷的需求已偏离但回归未跑，脚本需先同步：${blockedDefects.map((item) => item.title).join('、')}`
      : `${blockedDefects.length} defects drifted from the requirement — update the script before regression: ${blockedDefects.map((item) => item.title).join(', ')}`)
  }
  if (open.length === 0) {
    lines.push(t ? '✅ 没有待办：脚本全部自检、失败已归因、缺陷已闭环。' : '✅ Nothing open: all scripts verified, failures triaged, defects closed.')
  } else {
    for (const item of open) lines.push(`- ${item}`)
  }
  if (pendingStages.length > 0) {
    lines.push('')
    lines.push(t ? `未完成阶段（${pendingStages.length}/${STEP_IDS.length}）：${pendingStages.join('、')}` : `Unfinished stages (${pendingStages.length}/${STEP_IDS.length}): ${pendingStages.join(', ')}`)
  }
  lines.push('')
  return lines.join('\n')
}
